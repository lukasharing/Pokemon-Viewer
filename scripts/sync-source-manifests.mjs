import {readdir,readFile,writeFile} from "node:fs/promises";
import {resolve} from "node:path";
import {fileURLToPath} from "node:url";
import {applyConfiguredMetadata,buildManualKnowledge} from "./lib/pret-manifest.mjs";

const root=resolve(fileURLToPath(new URL("..",import.meta.url)));
const configDirectory=resolve(root,"manifests/config");
const generatedDirectory=resolve(root,"manifests/generated");
const names=(await readdir(configDirectory)).filter(name=>name.endsWith(".json")).sort();
const manifests=[];
const knowledgeById=new Map();

for(const name of names){
  const [config,manifest]=await Promise.all([
    readFile(resolve(configDirectory,name),"utf8").then(JSON.parse),
    readFile(resolve(generatedDirectory,name),"utf8").then(JSON.parse)
  ]);
  if(config.profile!==manifest.profile)throw new Error(`${name} config and generated profile do not match.`);
  const enriched=applyConfiguredMetadata(manifest,config);
  await writeFile(resolve(generatedDirectory,name),`${JSON.stringify(enriched,null,2)}\n`);
  manifests.push(enriched);
  const knowledge=buildManualKnowledge(config),previous=knowledgeById.get(knowledge.id);
  if(previous){
    const comparable=value=>JSON.stringify({
      schemaVersion:value.schemaVersion,id:value.id,family:value.family,method:value.method,
      evidence:value.evidence,platform:value.platform,repository:value.repository,
      symbolMetadata:value.symbolMetadata,structures:value.structures,resources:value.resources
    });
    if(comparable(previous)!==comparable(knowledge)){
      throw new Error(`Manual knowledge '${knowledge.id}' conflicts between profile configs.`);
    }
    knowledgeById.set(knowledge.id,Object.freeze({
      ...previous,
      profiles:Object.freeze([...new Set([...previous.profiles,...knowledge.profiles])])
    }));
  }else knowledgeById.set(knowledge.id,knowledge);
}

const browserSource=`// Generated by scripts/sync-source-manifests.mjs. Do not edit offsets here.
(function(global){
  "use strict";

  const freeze=value=>{
    if(!value||typeof value!=="object"||Object.isFrozen(value))return value;
    for(const item of Object.values(value))freeze(item);
    return Object.freeze(value);
  };
  const manifests=${JSON.stringify(manifests,null,2)}.map(freeze);
  const byFingerprint=new Map(manifests.map(manifest=>[manifest.fingerprint,manifest]));
  const byProfile=new Map();
  for(const manifest of manifests){
    const entries=byProfile.get(manifest.profile)||[];
    entries.push(manifest);byProfile.set(manifest.profile,Object.freeze(entries));
  }
  const get=fingerprint=>byFingerprint.get(String(fingerprint||"").toLowerCase())||null;
  const profiles=profile=>byProfile.get(String(profile||""))||Object.freeze([]);
  const symbol=(fingerprint,name)=>get(fingerprint)?.symbols[name]||null;
  const resource=(fingerprint,id)=>get(fingerprint)?.resources[id]||null;

  global.SourceManifestRegistry=Object.freeze({all:Object.freeze(manifests),get,profiles,symbol,resource});
  ((global.PokemonViewer||={}).core||={}).SourceManifestRegistry=global.SourceManifestRegistry;
})(globalThis);
`;
await writeFile(resolve(root,"js/core/source-manifest-registry.js"),browserSource);
const knowledge=[...knowledgeById.values()];
const knowledgeSource=`// Generated by scripts/sync-source-manifests.mjs. Contains no ROM offsets.
(function(global){
  "use strict";

  const freeze=value=>{
    if(!value||typeof value!=="object"||Object.isFrozen(value))return value;
    for(const item of Object.values(value))freeze(item);
    return Object.freeze(value);
  };
  const entries=${JSON.stringify(knowledge,null,2)}.map(freeze);
  const byId=new Map(entries.map(entry=>[entry.id,entry]));
  const byProfile=new Map();
  for(const entry of entries){
    byProfile.set(entry.id,entry);
    for(const profile of entry.profiles)byProfile.set(profile,entry);
  }
  const get=id=>byProfile.get(String(id||""))||null;
  const schema=(id,name)=>get(id)?.symbolMetadata?.[name]||null;
  const structure=(id,name)=>get(id)?.structures?.[name]||null;
  const resource=(id,name)=>get(id)?.resources?.[name]||null;

  global.ManualKnowledgeRegistry=Object.freeze({all:Object.freeze(entries),get,schema,structure,resource});
  ((global.PokemonViewer||={}).core||={}).ManualKnowledgeRegistry=global.ManualKnowledgeRegistry;
})(globalThis);
`;
await writeFile(resolve(root,"js/core/manual-knowledge-registry.js"),knowledgeSource);
console.log(`Synchronized ${manifests.length} exact manifests and ${knowledge.length} offset-free manual engine contracts.`);
